USE MODELOCLASSICO;

-- 1. Nome do cliente e valor total pago


SELECT CL.NOME_DO_CLIENTE, SUM(PG.MONTANTE_PAGO) AS TOTAL_PAGO
FROM CLIENTES CL
JOIN PAGAMENTOS PG ON CL.CLIENTE_ID = PG.CLIENTE_ID
GROUP BY CL.CLIENTE_ID, CL.NOME_DO_CLIENTE;


-- 2. Nome do funcionário e total de clientes atendidos


SELECT CONCAT(F.PRIMEIRO_NOME, ' ', F.ULTIMO_NOME) AS FUNCIONARIO,
COUNT(CL.CLIENTE_ID) AS TOTAL_CLIENTES
FROM FUNCIONARIOS F
JOIN CLIENTES CL ON F.FUNCIONARIO_ID = CL.FUNCIONARIO_ID
GROUP BY F.FUNCIONARIO_ID, F.PRIMEIRO_NOME, F.ULTIMO_NOME;


-- 3. Nome do produto e quantidade total vendida


SELECT P.NOME, SUM(DP.QUANTIDADE_ENCOMENDADA) AS QUANTIDADE_VENDIDA
FROM PRODUTOS P
JOIN DETALHES_DO_PEDIDO DP ON P.PRODUTO_ID = DP.PRODUTO_ID
GROUP BY P.PRODUTO_ID, P.NOME;


-- 4. Quantidade de funcionários por cidade


SELECT E.CIDADE, COUNT(F.FUNCIONARIO_ID) AS TOTAL_FUNCIONARIOS
FROM ESCRITORIOS E
JOIN FUNCIONARIOS F ON E.ESCRITORIO_ID = F.ESCRITORIO_ID
GROUP BY E.ESCRITORIO_ID, E.CIDADE;