-- 1. Maior preço sugerido

USE MODELOCLASSICO;

SELECT MAX(PRECO_SUGERIDO) AS MAIOR_PRECO_SUGERIDO
FROM PRODUTOS;

-- 2. Menor preço de custo

SELECT MIN(PRECO_DE_COMPRA) AS MENOR_PRECO_DE_COMPRA
FROM PRODUTOS;


-- 3. Preço sugerido médio por linha de produto

SELECT LINHA_DO_PRODUTO, AVG(PRECO_SUGERIDO) AS PRECO_SUGERIDO_MEDIO
FROM PRODUTOS
GROUP BY LINHA_DO_PRODUTO;

-- 4. Quantidade total em estoque por linha de produto

SELECT LINHA_DO_PRODUTO, SUM(QUANTIA_EM_ESTOQUE) AS TOTAL_EM_ESTOQUE
FROM PRODUTOS
GROUP BY LINHA_DO_PRODUTO;

