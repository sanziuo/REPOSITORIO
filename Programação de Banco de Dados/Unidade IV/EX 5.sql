
use sakila_pt;

SELECT * FROM filme;

-- 1. Quantidade total de filmes
SELECT COUNT(*) AS TOTAL_FILMES
FROM FILME;

-- 2. Duração média dos filmes
SELECT AVG(DURACAO_DO_FILME) AS DURACAO_MEDIA
FROM FILME;

-- 3. Quantidade total de filmes por categoria
SELECT * FROM CATEGORIA;
SELECT * FROM FILME_CATEGORIA;

SELECT C.NOME AS CATEGORIA, COUNT(FC.FILME_ID) AS TOTAL_FILMES
FROM CATEGORIA C
JOIN FILME_CATEGORIA FC ON C.CATEGORIA_ID = FC.CATEGORIA_ID
GROUP BY C.NOME;

-- 4. Duração média dos filmes por categoria

SELECT C.NOME AS CATEGORIA, AVG(F.DURACAO_DO_FILME) AS DURACAO_MEDIA
FROM CATEGORIA C
JOIN FILME_CATEGORIA FC ON C.CATEGORIA_ID = FC.CATEGORIA_ID
JOIN FILME F ON FC.FILME_ID = F.FILME_ID
GROUP BY C.NOME;

-- 5. Categorias com menos de 57 filmes

SELECT C.NOME AS CATEGORIA, COUNT(FC.FILME_ID) AS TOTAL_FILMES
FROM CATEGORIA C
JOIN FILME_CATEGORIA FC ON C.CATEGORIA_ID = FC.CATEGORIA_ID
GROUP BY C.NOME
HAVING COUNT(FC.FILME_ID) < 57;

