QTD_OLD INT, QTD_NEW INT, DATA_UPDT DATETIME,
PRIMARY KEY(ID));

DROP TRIGGER BF_UPT_PRODUTO;

DELIMITER $$
CREATE TRIGGER BF_UPT_PRODUTO
	BEFORE UPDATE ON PRODUTOS
    FOR EACH ROW -- STATEMENT SÓ SERÁ EXECUTADO PARA ESTA SENTENÇA || ROW PARA TODAS LINHAS TODOS REGISTROS.
    BEGIN
		INSERT INTO AUDIT_ESTOQUE
        VALUES (NULL, OLD.PRODUTO_ID, OLD.QUANTIA_EM_ESTOQUE, NEW.QUANTIA_EM_ESTOQUE, NOW());
    END $$
DELIMITER ;

