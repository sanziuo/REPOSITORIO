DROP VIEW VENDAS_POR_PRODUTO;

CREATE VIEW VENDAS_POR_PRODUTO
AS
SELECT PRODUTO_ID, SUM(QUANTIDADE_ENCOMENDADA * PRECO_DA_UNIDADE) AS TOTAL
FROM DETALHES_DO_PEDIDO
GROUP BY PRODUTO_ID
ORDER BY TOTAL DESC;

