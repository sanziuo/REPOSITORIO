-- AS FUNCÇÕES SÃO PARECIDAS COMO PROCEDURE. MAS SÃO CHAMADAS DIFERENTE.
--
DELIMITER $$
CREATE FUNCTION LUCRO(valor DECIMAL(10.2))
RETURNS DECIMAL(10,2)
DETERMINISTIC
BEGIN
	DECLARE LUCRO DECIMAL(10,2);
	SET LUCRO = valor* 1.1;
    RETURN LUCRO;
END $$
DELIMITER ;

SELECT PRECO_DE_COMPRA, LUCRO(PRECO_DE_COMPRA) AS LUCRO FROM PRODUTOS;