DELIMITER $$
CREATE PROCEDURE CONSULTA_PRECO(IN ID VARCHAR (15))
BEGIN
	-- CORPO DA PROCEDURE;
	SELECT PRECO_SUGERIDO AS PRECO FROM PRODUTOS WHERE PRODUTO_ID = ID;
END $$
DELIMITER ;

