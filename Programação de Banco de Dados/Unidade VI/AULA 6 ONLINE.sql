DROP PROCEDURE QUANTIDADE;

DELIMITER $$
CREATE PROCEDURE QUANTIDADE(OUT QTD INT)
BEGIN
	-- CORPO DA PROCEDURE;
	SELECT sum(QUANTIA_EM_ESTOQUE) INTO QTD FROM PRODUTOS;
END $$
DELIMITER ;

SET @ESTOQUE=0;

CALL QUANTIDADE(@ESTOQUE);

SELECT @ESTOQUE;

DROP PROCEDURE METADE;

-- PROCEDURE PARA IN/OUT
DELIMITER $$
CREATE PROCEDURE METADE(INOUT VALOR INT)
BEGIN
	-- CORPO DA PROCEDURE;
	SET VALOR = VALOR/2;
END $$
DELIMITER ;

SET @VALOR = 100;
CALL METADE(@VALOR);
SELECT @VALOR;

